#!/usr/bin/env python3
"""Generate train-only EV logging configs for UMR utility calibration.

The generated configs are evaluation/inference configs, not training configs.
They point ``data.test`` to nuScenes train infos and optionally insert
``OnlineSyntheticMultiCorrupt`` into the test pipeline so Phase-1 utility
calibration can collect train-clean and train-O.C sidecar logs without touching
val/corrupted-val data.
"""

import argparse
import os
import pprint
import re


FORBIDDEN_INPUT_MARKERS = (
    "nuscenes_infos_val",
    "multicorrupt_results",
    "targeted_probe",
    "corrupted_val",
    "corrupted-val",
    "validation",
)

COLLECT3D_DEFAULT_META_KEYS = (
    "filename", "ori_shape", "img_shape", "lidar2img",
    "depth2img", "cam2img", "pad_shape", "scale_factor", "flip",
    "pcd_horizontal_flip", "pcd_vertical_flip", "box_mode_3d",
    "box_type_3d", "img_norm_cfg", "pcd_trans", "sample_idx",
    "pcd_scale_factor", "pcd_rotation", "pcd_rotation_angle",
    "pts_filename", "transformation_3d_flow", "trans_mat", "affine_aug",
)


def _path_tokens(path):
    text = str(path).lower().replace("\\", "/")
    parts = []
    for item in text.split("/"):
        parts.extend(re.split(r"[_\-.]+", item))
    return {item for item in parts if item}


def assert_train_only(path, label):
    text = str(path).lower()
    bad = [marker for marker in FORBIDDEN_INPUT_MARKERS if marker in text]
    tokens = _path_tokens(path)
    if "val" in tokens:
        bad.append("path_token=val")
    if "corrupted" in tokens and "val" in tokens:
        bad.append("path_token=corrupted-val")
    if bad:
        raise SystemExit(
            f"[ERROR] Refusing val/corrupted-val-like {label}: {path}; markers={bad}"
        )
    if label == "train infos" and "train" not in os.path.basename(path).lower():
        raise SystemExit(
            f"[ERROR] Refusing non-train infos for formal Phase 1: {path}"
        )


def to_plain(obj):
    if isinstance(obj, dict):
        return {key: to_plain(value) for key, value in obj.items()}
    if isinstance(obj, list):
        return [to_plain(value) for value in obj]
    if isinstance(obj, tuple):
        return tuple(to_plain(value) for value in obj)
    return obj


def validate_test_aug_pipeline(pipeline):
    for step in pipeline:
        if not isinstance(step, dict):
            continue
        if step.get("type") == "MultiScaleFlipAug3D":
            img_scale = step.get("img_scale")
            if img_scale is not None and not isinstance(img_scale, tuple):
                raise SystemExit(
                    "[ERROR] MultiScaleFlipAug3D.img_scale must remain a tuple. "
                    f"Got {type(img_scale).__name__}: {img_scale!r}"
                )
        transforms = step.get("transforms")
        if isinstance(transforms, list):
            validate_test_aug_pipeline(transforms)


def ensure_oc_meta_keys(pipeline):
    """Add O.C metadata keys to nested Collect3D transforms."""
    meta_keys = ("synthetic_corruption", "corruption_type", "corruption_severity")
    for step in pipeline:
        if not isinstance(step, dict):
            continue
        if step.get("type") == "Collect3D":
            current = list(step.get("meta_keys") or COLLECT3D_DEFAULT_META_KEYS)
            for key in meta_keys:
                if key not in current:
                    current.append(key)
            step["meta_keys"] = tuple(current)
        transforms = step.get("transforms")
        if isinstance(transforms, list):
            ensure_oc_meta_keys(transforms)


def insert_online_corrupt(pipeline, oc_cfg):
    out = []
    inserted = False
    for step in pipeline:
        out.append(step)
        if isinstance(step, dict) and step.get("type") == "LoadMultiViewImageFromFiles":
            out.append(dict(oc_cfg))
            inserted = True
    if not inserted:
        raise SystemExit(
            "[ERROR] Could not insert OnlineSyntheticMultiCorrupt after "
            "LoadMultiViewImageFromFiles in test pipeline."
        )
    ensure_oc_meta_keys(out)
    return out


def write_config(path, base_config, train_infos, pipeline, workers_per_gpu,
                 samples_per_gpu, work_dir, note):
    rel_base = os.path.relpath(os.path.abspath(base_config), os.path.dirname(os.path.abspath(path)))
    payload = [
        "# Auto-generated by tools/make_umr_phase1_log_configs.py",
        "# Train-only UMR utility-calibration logging config.",
        f"# {note}",
        f"_base_ = [{rel_base!r}]",
        "",
        "data = dict(",
        f"    samples_per_gpu={int(samples_per_gpu)},",
        f"    workers_per_gpu={int(workers_per_gpu)},",
        "    test_dataloader=dict(",
        f"        samples_per_gpu={int(samples_per_gpu)},",
        f"        workers_per_gpu={int(workers_per_gpu)}),",
        "    test=dict(",
        "        test_mode=True,",
        f"        ann_file={train_infos!r},",
        f"        pipeline={pprint.pformat(pipeline, width=100, sort_dicts=False)},",
        "    ),",
        ")",
        "",
        f"work_dir = {work_dir!r}",
        "",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(payload))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-config", required=True)
    parser.add_argument("--train-infos", default="data/nuscenes/nuscenes_infos_train.pkl")
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--workers-per-gpu", type=int, default=8)
    parser.add_argument("--samples-per-gpu", type=int, default=1)
    parser.add_argument("--oc-corrupt-prob", type=float, default=0.50)
    parser.add_argument("--oc-severities", default="1,2,3")
    parser.add_argument(
        "--oc-weights",
        default=(
            "beamsreducing=0.24,pointsreducing=0.16,spatialmisalignment=0.13,"
            "temporalmisalignment=0.09,fog=0.14,snow=0.08,brightness=0.04,"
            "dark=0.05,motionblur=0.05,missingcamera=0.02"
        ),
    )
    args = parser.parse_args()

    assert_train_only(args.base_config, "base config")
    assert_train_only(args.train_infos, "train infos")
    if not os.path.isfile(args.base_config):
        raise SystemExit(f"[ERROR] Missing base config: {args.base_config}")
    if not os.path.isfile(args.train_infos):
        raise SystemExit(f"[ERROR] Missing train infos: {args.train_infos}")

    try:
        from mmcv import Config
    except ImportError as exc:
        raise SystemExit(
            "[ERROR] mmcv is required to resolve inherited configs. "
            "Run this inside the MEFormerv2/meformer conda environment."
        ) from exc

    cfg = Config.fromfile(args.base_config)
    pipeline = to_plain(cfg.data.test.pipeline)
    ensure_oc_meta_keys(pipeline)
    validate_test_aug_pipeline(pipeline)

    weights = {}
    for item in args.oc_weights.split(","):
        item = item.strip()
        if not item:
            continue
        key, value = item.split("=", 1)
        weights[key.strip()] = float(value)
    severities = [int(item.strip()) for item in args.oc_severities.split(",") if item.strip()]
    oc_cfg = dict(
        type="OnlineSyntheticMultiCorrupt",
        corrupt_prob=float(args.oc_corrupt_prob),
        severity_choices=severities,
        corruption_weights=weights,
        record_meta=True,
    )
    oc_pipeline = insert_online_corrupt([dict(step) for step in pipeline], oc_cfg)
    validate_test_aug_pipeline(oc_pipeline)

    os.makedirs(args.out_dir, exist_ok=True)
    clean_path = os.path.join(args.out_dir, "umr_phase1_train_clean_log.py")
    oc_path = os.path.join(args.out_dir, "umr_phase1_train_oc_log.py")
    work_dir = os.path.join(os.path.dirname(args.out_dir), "work")

    write_config(
        clean_path, args.base_config, args.train_infos, pipeline,
        args.workers_per_gpu, args.samples_per_gpu, work_dir,
        "Clean train split; no online corruption.")
    write_config(
        oc_path, args.base_config, args.train_infos, oc_pipeline,
        args.workers_per_gpu, args.samples_per_gpu, work_dir,
        "Train split with OnlineSyntheticMultiCorrupt inserted before test transforms.")

    manifest = os.path.join(args.out_dir, "phase1_log_configs.tsv")
    with open(manifest, "w", encoding="utf-8") as f:
        f.write("condition\tconfig\tformal_split\toc_corrupt_prob\toc_severities\n")
        f.write(f"train_clean\t{clean_path}\ttrain\t0\t0\n")
        f.write(
            f"train_oc\t{oc_path}\ttrain\t{args.oc_corrupt_prob}\t"
            f"{','.join(str(s) for s in severities)}\n")
    print(f"[UMR Phase1] wrote clean config: {clean_path}")
    print(f"[UMR Phase1] wrote train-O.C config: {oc_path}")
    print(f"[UMR Phase1] wrote manifest: {manifest}")


if __name__ == "__main__":
    main()
